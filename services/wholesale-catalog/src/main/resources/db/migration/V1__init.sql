CREATE TABLE categories (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(100) NOT NULL,
    parent_id BIGINT REFERENCES categories (id)
);

CREATE TABLE products (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wholesaler_id VARCHAR(64)    NOT NULL,
    name          VARCHAR(200)   NOT NULL,
    description   VARCHAR(2000),
    category_id   BIGINT         NOT NULL REFERENCES categories (id),
    moq           INTEGER        NOT NULL CHECK (moq >= 1),
    base_price    NUMERIC(12, 2) NOT NULL CHECK (base_price > 0),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_products_wholesaler ON products (wholesaler_id);
CREATE INDEX idx_products_category ON products (category_id);

-- Bulk pricing: from min_qty units upward, each unit costs unit_price.
CREATE TABLE price_tiers (
    product_id BIGINT         NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    min_qty    INTEGER        NOT NULL CHECK (min_qty >= 1),
    unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price > 0),
    PRIMARY KEY (product_id, min_qty)
);
